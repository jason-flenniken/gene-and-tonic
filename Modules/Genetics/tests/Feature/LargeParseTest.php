<?php

use Illuminate\Support\Facades\File;
use Modules\Genetics\Support\Parsing\TwentyThreeAndMeParser;

/*
 * Opt-in: a 640k-line 23andMe export must stream through the parser within the
 * memory and time budget (NFR-01). Run with RUN_LARGE_PARSE_TESTS=1.
 */
it('parses a 640k-line 23andMe export within 128 MB and 120 seconds', function () {
    $directory = sys_get_temp_dir().DIRECTORY_SEPARATOR.'genetics-large-'.uniqid();
    $path = $directory.DIRECTORY_SEPARATOR.'23andme-640k.txt';
    $lineCount = 640_000;

    File::makeDirectory($directory);

    try {
        $handle = fopen($path, 'wb');
        fwrite($handle, "# This data file generated by 23andMe\n# Synthetic large-file fixture\n");
        for ($line = 1; $line <= $lineCount; $line++) {
            fwrite($handle, sprintf("rs%d\t1\t%d\tAG\n", $line, $line * 10));
        }
        fclose($handle);

        $started = microtime(true);
        $parsed = iterator_count((new TwentyThreeAndMeParser)->parse($path));
        $elapsed = microtime(true) - $started;

        expect($parsed)->toBe($lineCount)
            ->and(memory_get_peak_usage())->toBeLessThan(128 * 1024 * 1024)
            ->and($elapsed)->toBeLessThan(120.0);
    } finally {
        File::deleteDirectory($directory);
    }
})->skip(fn () => getenv('RUN_LARGE_PARSE_TESTS') !== '1', 'Set RUN_LARGE_PARSE_TESTS=1 to run the large parse test.');
